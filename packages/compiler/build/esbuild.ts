// Thin esbuild wrapper used by the dev asset pipeline.
//
// esbuild is the workhorse for the M4 dev asset pipeline: it
// bundles the runtime, islands, and stylesheet on demand. This
// module is a tiny, deterministic wrapper that:
//
//   1. allocates a unique tmp `outdir` (esbuild cannot bundle to
//      memory with `write: false` once there is more than one
//      entry point or once a separate source map is requested);
//   2. runs `esbuild.build` with @ggpwnkthx/esbuild and the
//      @ggpwnkthx/esbuild-plugin-deno resolver / loader plugin, so
//      entries can import from JSR / npm / local `file:` URLs the
//      same way `deno run` would;
//   3. reads the produced JS bytes (and the matching `.map` when
//      `sourceMap` is set to anything other than `false` or
//      `"inline"`);
//   4. walks the esbuild `metafile.inputs` to capture the absolute
//      path and `mtime.getTime()` of every file that contributed
//      to the bundle (these are the inputs the dev cache
//      invalidates on);
//   5. cleans up the tmp `outdir`;
//   6. stops esbuild's native child process so tests and short-lived
//      build commands do not hang after the build completes.
//
// `esbuildBundle` is a pure function over the entry points. The
// dev cache (`build/cache.ts`) is what holds the result.
//
// Permissions: the wrapper opens the on-disk `outdir` for writing,
// so callers must run with `--allow-write` (and `--allow-read` for
// the entry files). @ggpwnkthx/esbuild also executes the cached
// native esbuild binary, so build/dev callers must include
// `--allow-run`. A cold binary install or remote module fetch may
// also need `--allow-net`.
import * as esbuild from "esbuild";
import { denoPlugin } from "@ggpwnkthx/esbuild-plugin-deno";
import { dirname, fromFileUrl, isAbsolute, join, normalize } from "@std/path";
import { CompilerError } from "../errors.ts";

/**
 * Absolute path of the directory that holds the virtual island
 * entry tmp files generated by the dev asset pipeline. The path is
 * derived from `TMPDIR` so the files live in a system tmp dir,
 * not the user's project directory (`discoverProject` would
 * otherwise pick a leftover file up as a third island).
 *
 * Exported so `build/dev_assets.ts` and the filter in
 * `esbuildBundle` share one source of truth. The dev cache must
 * NOT track files in this directory as part of a bundle's input
 * set: the file's lifetime is bounded by the bundler, not the
 * user's edits, and a missing or recreated file (e.g. across test
 * runs that delete the tmp dir in cleanup) would otherwise force
 * spurious cache invalidation.
 */
export const VIRTUAL_ENTRY_DIR: string = (() => {
  const base = Deno.env.get("TMPDIR") ?? "/tmp";
  // Normalize a trailing slash so the prefix check below does not
  // have to think about it.
  const trimmed = base.endsWith("/") ? base.slice(0, -1) : base;
  return `${trimmed}/sprout-virtual-entries`;
})();

/** True when `path` lives inside {@link VIRTUAL_ENTRY_DIR}. */
function isInsideVirtualEntryDir(path: string): boolean {
  // The trailing separator disambiguates `/tmp/sprout-virtual-entries-evil`
  // from `/tmp/sprout-virtual-entries/<file>`. esbuild's metafile
  // reports absolute paths, so a plain prefix check on the
  // directory works.
  return path === VIRTUAL_ENTRY_DIR ||
    path.startsWith(`${VIRTUAL_ENTRY_DIR}/`);
}

/** Options accepted by {@link esbuildBundle}. */
export type EsbuildBundleOptions = {
  /** Absolute on-disk paths to the entry files. esbuild reads these directly. */
  readonly entryPoints: readonly string[];
  /** JSX import source for `jsxImportSource` automatic transform. */
  readonly jsxImportSource: string;
  /** esbuild build target. Defaults to `"es2022"`. */
  readonly target?: string;
  /** Minify the output. Defaults to `false`. */
  readonly minify?: boolean;
  /**
   * Source map mode. Defaults to `"external"`, which produces a
   * companion `.map` file. `"inline"` embeds the map in the JS
   * output. `"false"` (or just `false`) omits the source map.
   */
  readonly sourceMap?: boolean | "inline" | "external" | "linked" | "both";
  /**
   * Optional file-loader overrides. The dev pipeline uses
   * `loader: { ".css": "css" }` for the stylesheet asset.
   */
  readonly loader?: Readonly<Record<string, esbuild.Loader>>;
  /**
   * Absolute path to a `deno.json` / `deno.jsonc` config file
   * that should anchor the Deno resolver. When the dev pipeline
   * writes a virtual entry outside the user's project directory
   * (so `discoverProject` cannot pick it up), the resolver can no
   * longer walk up from the entry path to find the workspace
   * config — it has to be told explicitly. The dev pipeline looks
   * up the nearest config by walking up from the original entry's
   * parent dir and passes the path through this option.
   */
  readonly denoConfigPath?: string;
};

/** A single input that contributed to the bundle, with its mtime. */
export type EsbuildBundleInput = {
  readonly path: string;
  /** mtime in milliseconds since epoch. `0` when the file was unreadable. */
  readonly mtime: number;
};

/** Result of {@link esbuildBundle}. */
export type EsbuildBundleResult = {
  /** Bundled JS bytes. Always populated. */
  readonly code: Uint8Array;
  /** Bundled source map bytes. `null` when the caller did not request a map. */
  readonly map: Uint8Array | null;
  /** Inputs that fed the bundle, sorted by absolute path. */
  readonly inputs: readonly EsbuildBundleInput[];
};

/**
 * Stop the native esbuild service. @ggpwnkthx/esbuild keeps a child
 * process alive between API calls; tests and one-shot commands must
 * stop it explicitly or the Deno process can hang.
 */
export async function stopEsbuild(): Promise<void> {
  await esbuild.stop();
}

async function stopEsbuildBestEffort(): Promise<void> {
  try {
    await stopEsbuild();
  } catch (_cause) {
    // best-effort child-process cleanup
  }
}

function importerToFilePath(importer: string): string | null {
  if (importer.length === 0) {
    return null;
  }
  if (importer.startsWith("file://")) {
    try {
      return fromFileUrl(importer);
    } catch (_cause) {
      return null;
    }
  }
  if (isAbsolute(importer)) {
    return importer;
  }
  if (importer.includes("://")) {
    return null;
  }

  const candidate = join(Deno.cwd(), importer);
  try {
    const stat = Deno.statSync(candidate);
    return stat.isFile ? candidate : null;
  } catch (_cause) {
    return null;
  }
}

function resolveRelativeFile(baseDir: string, specifier: string): string | null {
  const base = normalize(join(baseDir, specifier));
  const candidates = [
    base,
    `${base}.ts`,
    `${base}.tsx`,
    `${base}.js`,
    `${base}.jsx`,
    `${base}.mjs`,
    `${base}.mts`,
    join(base, "index.ts"),
    join(base, "index.tsx"),
    join(base, "index.js"),
    join(base, "index.jsx"),
  ];
  for (const candidate of candidates) {
    try {
      const stat = Deno.statSync(candidate);
      if (stat.isFile) {
        return candidate;
      }
    } catch (_cause) {
      // Try the next candidate.
    }
  }
  return null;
}

function relativeFileImportPlugin(): esbuild.Plugin {
  return {
    name: "sprout-relative-file-imports",
    setup(build) {
      build.onResolve({ filter: /^\.+\// }, (args) => {
        const importer = importerToFilePath(args.importer);
        if (importer === null) {
          return null;
        }
        const resolved = resolveRelativeFile(dirname(importer), args.path);
        if (resolved === null) {
          return null;
        }
        return { path: resolved };
      });
    },
  };
}

/**
 * Bundle the supplied entry points with esbuild + the Deno resolver /
 * loader plugin. The function is `async` because `esbuild.build` is
 * async; the rest is straight-line.
 *
 * Errors from esbuild are wrapped as `CompilerError("BUILD_FAILED", ...)`.
 */
export async function esbuildBundle(
  opts: EsbuildBundleOptions,
): Promise<EsbuildBundleResult> {
  if (opts.entryPoints.length === 0) {
    throw new CompilerError(
      "BUILD_FAILED",
      "esbuildBundle requires at least one entry point",
      { entryPoints: opts.entryPoints },
    );
  }
  const outdir = await Deno.makeTempDir({ prefix: "sprout-esbuild-" });
  const cleanup = async (): Promise<void> => {
    try {
      await Deno.remove(outdir, { recursive: true });
    } catch (_cause) {
      // best-effort cleanup
    }
  };
  const sourceMap = opts.sourceMap ?? "external";
  try {
    const result = await esbuild.build({
      entryPoints: [...opts.entryPoints],
      outdir,
      bundle: true,
      format: "esm",
      target: opts.target ?? "es2022",
      jsx: "automatic",
      jsxImportSource: opts.jsxImportSource,
      minify: opts.minify ?? false,
      sourcemap: sourceMap,
      metafile: true,
      write: true,
      loader: opts.loader,
      plugins: [
        relativeFileImportPlugin(),
        denoPlugin({
          configPath: opts.denoConfigPath,
          // Let esbuild own TS/JSX lowering so the wrapper's explicit
          // jsxImportSource option remains the single source of truth.
          noTranspile: true,
        }) as unknown as esbuild.Plugin,
      ],
    });

    // esbuild writes one .js per entry point; the bundle we return
    // is the first entry's output. The M4 dev pipeline always
    // bundles exactly one entry per call, so the first output is
    // the only one that matters. We sort by key to keep the order
    // stable across runs.
    const meta = result.metafile;
    if (meta === undefined) {
      throw new CompilerError("BUILD_FAILED", "esbuild did not return a metafile", {});
    }
    const outputs = Object.keys(meta.outputs).sort();
    const jsOutput = outputs.find((p) => p.endsWith(".js"));
    if (jsOutput === undefined) {
      throw new CompilerError(
        "BUILD_FAILED",
        "esbuild did not produce a .js output",
        { outputs },
      );
    }
    const jsPath = `${outdir}/${jsOutput}`;
    const code = await Deno.readFile(jsPath);
    let map: Uint8Array | null = null;
    if (sourceMap !== false && sourceMap !== "inline") {
      const mapPath = `${jsPath}.map`;
      try {
        map = await Deno.readFile(mapPath);
      } catch (_cause) {
        map = null;
      }
    }
    // Walk the metafile inputs. esbuild reports every on-disk
    // file that participated in the bundle. We re-stat each path
    // to capture the mtime; the dev cache uses mtime as the
    // invalidation signal.
    //
    // The virtual island entry lives in VIRTUAL_ENTRY_DIR, which
    // is a build implementation detail: the file is generated per
    // call, its lifetime is bounded by the bundler, and a leftover
    // or missing file from a prior run would otherwise force the
    // dev cache to invalidate spuriously. The dev cache is meant
    // to track the user's source files, so the virtual entry is
    // dropped from the input set here. See
    // `compileIsland` in `build/dev_assets.ts` for the matching
    // rule that the tmp file is kept on disk across calls.
    const inputs: EsbuildBundleInput[] = [];
    for (const relPath of Object.keys(meta.inputs).sort()) {
      const entry = meta.inputs[relPath];
      // The metafile reports inputs as the paths esbuild saw
      // them, which can be relative. Resolve against the entry
      // directory (the first entry's parent) so the path is
      // stable for `Deno.stat`.
      const firstEntry = opts.entryPoints[0] as string;
      const entryDir = firstEntry.includes("/")
        ? firstEntry.slice(0, firstEntry.lastIndexOf("/"))
        : ".";
      const absPath = relPath.startsWith("/") ? relPath : `${entryDir}/${relPath}`;
      if (isInsideVirtualEntryDir(absPath)) {
        // Skip the virtual entry; see the comment above.
        void entry;
        continue;
      }
      let mtime = 0;
      try {
        const stat = Deno.statSync(absPath);
        mtime = stat.mtime?.getTime() ?? 0;
      } catch (_cause) {
        mtime = 0;
      }
      inputs.push({ path: absPath, mtime });
      // Touch the unused meta var so the linter does not flag
      // the destructured property as dead code.
      void entry;
    }
    return { code, map, inputs };
  } catch (cause) {
    if (cause instanceof CompilerError) {
      throw cause;
    }
    const errors = (cause as { errors?: unknown }).errors;
    const message = cause instanceof Error ? cause.message : String(cause);
    throw new CompilerError("BUILD_FAILED", message, {
      errors: errors as unknown,
    });
  } finally {
    await cleanup();
    await stopEsbuildBestEffort();
  }
}
