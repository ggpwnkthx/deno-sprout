// Virtual module generators for the dev asset pipeline.
//
// Islands are bundled by esbuild with a generated entry file that
// imports the user's island module by absolute path and wraps the
// default export in a `{ mount(element, props) }` object the
// browser runtime can call. The wrapper is exported for tests so
// they can assert on the generated source without bundling.
//
// The runtime entry is the existing `packages/compiler/runtime_entry.ts`
// file, which the M4 compiler compiles as-is. The M3 file is a
// no-op stub; the M4 compiler does not (yet) generate a `mountAll`
// call site for the runtime. The dev asset simply embeds the
// current file, which the M5+ work can replace.

/** Inputs to {@link buildIslandVirtualEntry}. */
export type BuildIslandVirtualEntryOptions = {
  /** Absolute path of the user's island source file. */
  readonly componentFile: string;
  /**
   * Absolute path of the user's island source file, as it should
   * appear in the generated entry's `import` statement. The Deno
   * loader resolves file URLs from absolute paths, so the raw
   * absolute path is fine; the caller may also pass a `file:` URL.
   */
  readonly componentImportPath: string;
};

/** Result of {@link buildIslandVirtualEntry}. */
export type BuildIslandVirtualEntryResult = {
  /** Path of a tmp file holding the generated entry source. */
  readonly entryPath: string;
  /** The generated source code. */
  readonly content: string;
};

/**
 * Build the source for a virtual island entry. The output is a
 * self-contained TypeScript module that imports the user's island
 * component and exposes a `{ mount }` wrapper:
 *
 * ```ts
 * import Component from "<componentImportPath>";
 * import { mountComponent } from "@sprout/runtime";
 *
 * export default {
 *   mount(element: HTMLElement, props: Readonly<Record<string, unknown>>) {
 *     mountComponent(element, Component as (p: Readonly<Record<string, unknown>>) => unknown, props);
 *   },
 * };
 * ```
 *
 * The function does not write the source to disk. The caller is
 * responsible for materializing the entry file (and for deleting
 * it after esbuild reads it).
 */
export function buildIslandVirtualEntry(
  opts: BuildIslandVirtualEntryOptions,
): BuildIslandVirtualEntryResult {
  const content = [
    "// Generated by @sprout/compiler (M4 dev asset pipeline).",
    `import Component from ${JSON.stringify(opts.componentImportPath)};`,
    `import { mountComponent } from "@sprout/runtime";`,
    "",
    "export default {",
    "  mount(element: HTMLElement, props: Readonly<Record<string, unknown>>) {",
    "    mountComponent(",
    "      element,",
    "      Component as (p: Readonly<Record<string, unknown>>) => unknown,",
    "      props,",
    "    );",
    "  },",
    "};",
    "",
  ].join("\n");
  return {
    entryPath: opts.componentFile,
    content,
  };
}
